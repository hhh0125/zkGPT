"""Certify round(2^20 exp(-t/512)) with exact rational Taylor intervals.

For 0<=t<=8191, u=t/16384<=1/2. Alternating Taylor partial sums
P33(u)<=exp(-u)<=P32(u), both positive. Raising endpoints to 32
preserves order and gives exp(-t/512). Both interval endpoints round
to the same integer in every generated entry. No floating point.
For t>=8191, monotonicity and the certified zero at 8191 prove zero.
"""
from fractions import Fraction
from functools import lru_cache
import hashlib,json,pathlib,sys
def nearest_nonnegative(x):
 return (2*x.numerator+x.denominator)//(2*x.denominator)
@lru_cache(maxsize=None)
def _entry(t):
 u=Fraction(t,16384);term=Fraction(1);upper=Fraction(1)
 for k in range(1,33):
  term*=(-u)/k;upper+=term
 lower=upper+term*(-u)/33
 if not 0<lower<=upper:raise ArithmeticError('invalid exponential interval')
 lo=nearest_nonnegative((lower**32)*1048576)
 hi=nearest_nonnegative((upper**32)*1048576)
 if lo!=hi:raise ArithmeticError(('rounding not certified',t,lo,hi))
 return lo
def certified_value(t):
 if not isinstance(t,int) or not 0<=t<2**32:raise ValueError('Exp index must be u32')
 if t>=8191:
  if _entry(8191)!=0:raise ArithmeticError('Exp tail not certified zero')
  return 0
 return _entry(t)
def build_table():return [certified_value(t) for t in range(8192)]
def source(table):
 lines=['// Generated by tools/generate_exp_table.py using exact rational intervals.',
        '// St=2^-9, Se=2^-20; no clamp. Actual table addresses 0..8191.',
        'static constexpr std::uint32_t kUnclampedExp[8192] = {']
 for i in range(0,len(table),16):lines.append('    '+', '.join(map(str,table[i:i+16]))+',')
 return '\n'.join(lines+['};',''])
if __name__=='__main__':
 table=build_table();text=source(table)
 raw=b''.join(x.to_bytes(4,'little') for x in table)
 if len(sys.argv)==3 and sys.argv[1]=='--check':
  if pathlib.Path(sys.argv[2]).read_text()!=text:raise SystemExit('noncanonical Exp table')
 elif len(sys.argv)==2:pathlib.Path(sys.argv[1]).write_text(text,encoding='utf-8',newline='\n')
 else:raise SystemExit('usage: generate_exp_table.py [--check] exp_table.inc')
 print(json.dumps({'entries':len(table),'first':table[0],'last':table[-1],
  'first_zero':next(i for i,x in enumerate(table) if x==0),
  'sha256_u32_le':hashlib.sha256(raw).hexdigest(),'certificate':'exact-positive-P33-P32-power32-intervals'}))
